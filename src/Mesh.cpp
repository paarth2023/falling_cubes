#include "Mesh.h"
#include <glad/glad.h>

Mesh::Mesh(const float *vertices, unsigned int floatCount, unsigned int vertexCount, BufferLayout layout)
    : m_vao(VertexBuffer(vertices, floatCount), std::move(layout)),
      m_vertexCount(vertexCount)
{
}

void Mesh::draw() const
{
    m_vao.bind();
    glDrawArrays(GL_TRIANGLES, 0, m_vertexCount);
}

